import type { TaskContext } from "../rpc/protocol.gen.ts";

// Содержимое веб-страниц недоверенное (assistant-project.md §3.7): диалог, который его касался,
// идёт только на чтение — исполнитель не получает ни записи, ни команд, ни вопросов человеку о них.
// Диалог касался веба, если у его первой задачи контекст взят со страницы (здесь) или исполнитель
// в какой-то его задаче сам сходил в сеть (событие `web` исполнителя).

/** Контекст взят с веб-страницы: есть `url` любой схемы. Сюда же добавится текст страницы (LUNA-6). */
export function isWebContext(context: TaskContext | undefined): boolean {
  return context?.url !== undefined;
}
